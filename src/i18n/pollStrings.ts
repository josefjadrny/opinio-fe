// "{n} votes" with the language's plural rules (cs/pl have few/many forms).
export function plural(forms: Plural, locale: string, n: number, fmt: (n: number) => string = String): string {
  const cat = new Intl.PluralRules(locale).select(n) as keyof Plural | 'zero' | 'two';
  const tpl = cat === 'one' || cat === 'few' || cat === 'many' ? forms[cat] : forms.other;
  return tpl.replace('{n}', fmt(n));
}
